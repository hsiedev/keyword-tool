import assert from 'node:assert/strict';
import Brief from '../public/ai-brief.js';
import { requireBrief, personaPlanRequest, personaGenerateRequest } from '../ai-persona.mjs';
const A=Brief.adaptive, given=value=>({status:'given',value}), select=A.selectTopic;
assert.equal(A.route('제휴 체크카드').route,'card');
assert.equal(A.route('B2B 협업툴').route,'b2b');
assert.equal(A.route('치과 임플란트').route,'hospital');
assert.equal(A.route('병원 실비보험').kind,'ambiguous');
assert.equal(A.route('반려식물 구독').route,'generic');
assert.equal(A.route('   ').route,'');
const s=select(Brief.blankAdaptive(),'체크카드 신규 발급');
s.step=s.max=4;s.product='카드 가상 테스트';s.adaptive.goal='submit';s.adaptive.scenarios=[0];
s.adaptive.fields.eligibility=given('공식에서 확인한 자격 문구');
s.adaptive.fields.usage=given('비활성 사용처');
s.official='https://example.invalid/official';s.landing='https://example.invalid/apply';
assert.equal(Brief.firstProblem(s),null);
assert.deepEqual(A.extras(s).map(x=>x.id),['eligibility']);
let other=select(s,'다른 신용카드 한도');
assert.equal(A.draftCount(other),1); assert.equal(other.product,''); assert.equal(other.max,0);
assert(!JSON.stringify(Brief.forRequest(other)).includes('카드 가상 테스트'));
other=select(Brief.normalize(JSON.parse(JSON.stringify(other))),' 체크카드 신규 발급 ');
assert.equal(other.product,s.product); assert.equal(other.official,s.official);
assert.equal(other.adaptive.goal,'submit'); assert.deepEqual(other.adaptive.scenarios,[0]);
assert.equal(A.draftCount(other),0);
assert.equal(Brief.payload(other).topic,'체크카드 신규 발급');
assert.equal(Brief.payload(other).context.notes[0].answer,'공식에서 확인한 자격 문구');
assert(!JSON.stringify(Brief.forRequest(other)).includes('비활성 사용처'));
assert(!Brief.compose(other).includes('비활성 사용처'));
const cardPlan=personaPlanRequest(requireBrief(other));
assert(cardPlan.prompt.includes('공식에서 확인한 자격 문구'));
assert(!cardPlan.prompt.includes('비활성 사용처'));
assert(personaGenerateRequest(requireBrief(other),{personas:Brief.people(other),avoid:[]},{count:30}).prompt.includes('공식에서 확인한 자격 문구'));
other.adaptive.goal='compare';other.adaptive.scenarios=[2];
assert.deepEqual(A.extras(other).map(x=>x.id),['usage']);
assert(!Brief.compose(other).includes('공식에서 확인한 자격 문구'));
other.adaptive.goal='submit';other.personaMode='ai';
assert.deepEqual(A.extras(other).map(x=>x.id),['eligibility']);
assert(!JSON.stringify(Brief.forRequest(other)).includes('비활성 사용처'));
const mixed=select(other,'병원 실비보험');
assert.equal(Brief.firstProblem(mixed).step,0);
const manual=select(mixed,'병원 실비보험','hospital');
assert.equal(Brief.normalize(manual).adaptive.route,'hospital');
manual.adaptive.goal='visit';assert.deepEqual(A.extras(manual).map(x=>x.id),['area','scope']);
manual.adaptive.scenarios=[2];assert.deepEqual(A.extras(manual).map(x=>x.id),['area','scope','medicalLimits']);
const b2b=select(manual,'기업용 CRM 도입');
b2b.adaptive.goal='demo';b2b.adaptive.scenarios=[3];
assert.deepEqual(A.extras(b2b).map(x=>x.id),['buyer','companySize','security']);
const general=select(b2b,'반려식물 구독');
general.adaptive.productUnknown=true;general.product='숨긴 기존 상품';general.adaptive.goal='explore';general.personaMode='ai';
general.adaptive.questions=[{question:'어떤 배송 방식인가요?',answer:given('실제 가능한 배송만')},{question:'관리 안내를 주나요?',answer:{status:'unknown',value:'숨긴 기존 답변'}},{question:'',answer:given('숨긴 빈 질문 답변')}];
assert.equal(Brief.firstProblem(general),null);
assert.equal(Brief.payload(general).product,'미정');
assert.deepEqual(Brief.payload(general).context.notes.map(n=>n.status),['사용자 입력','미정']);
assert(!JSON.stringify(Brief.forRequest(general)).includes('숨긴'));
assert.deepEqual(A.questions(['  어떤 지역인가요? ','어떤 지역인가요?',42,'무엇인가요?', 'a'.repeat(111),'누구인가요?','초과']),['어떤 지역인가요?','무엇인가요?','누구인가요?']);
const legacy=Brief.normalize({v:1,topic:'card',product:'이전 상품',goal:'submit',picked:{card:[0]},step:4,max:4});
assert.equal(legacy.adaptive,undefined);assert.equal(Brief.firstProblem(legacy),null);
assert.equal(Brief.payload(legacy).product,'이전 상품');assert.equal(Brief.people(legacy).length,1);
assert.equal(Brief.forRequest(legacy).adaptive,undefined);
console.log('적응형 브리프: 주제·답변 분기, 초안 분리·복원, 미정, 생성 요청, 이전 브리프 호환 통과');
